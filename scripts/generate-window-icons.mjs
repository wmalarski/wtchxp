import { readFileSync, writeFileSync } from "node:fs";

// The XP title bar icons are pixel art with hundreds of one-pixel paths. Keep
// the SVG files as the source of truth and generate inline Solid components so
// the icons ship with the Window component instead of the global stylesheet.
const actions = ["Minimize", "Maximize", "Restore", "Help", "Close"];
const states = ["normal", "hover", "active"];

const readIcon = (name) => {
  const source = readFileSync(new URL(`../src/icons/${name}.svg`, import.meta.url), "utf8");
  const match = source.match(/<svg[^>]*\sviewBox="([^"]+)"[^>]*>([\s\S]*?)<\/svg>/);

  if (!match) {
    throw new Error(`Could not parse src/icons/${name}.svg`);
  }

  return { viewBox: match[1], body: match[2].trim() };
};

const indent = (value, spaces) =>
  value
    .split("\n")
    .map((line) => (line.trim() === "" ? line : `${" ".repeat(spaces)}${line.trim()}`))
    .join("\n");

const components = actions
  .map((action) => {
    const name = action.toLowerCase();
    const { viewBox } = readIcon(name);
    const groups = states
      .map((state, index) => {
        const suffix = index === 0 ? "" : `-${state}`;
        const { body } = readIcon(`${name}${suffix}`);

        return `    <g data-icon-state="${state}">\n${indent(body, 6)}\n    </g>`;
      })
      .join("\n");

    return `export type ${action}IconProps = ComponentProps<"svg">;

export const ${action}Icon: Component<${action}IconProps> = (props) => (
  <svg
    viewBox="${viewBox}"
    width="21"
    height="21"
    shape-rendering="crispEdges"
    aria-hidden="true"
    {...props}
  >
${groups}
  </svg>
);`;
  })
  .join("\n\n");

const output = `// This file is generated by scripts/generate-window-icons.mjs.
// Run \`vp run generate:icons\` after changing the title bar SVG files.
import type { ComponentProps } from "@solidjs/web";
import { type Component } from "solid-js";

${components}
`;

writeFileSync(new URL("../src/window/window-icons.tsx", import.meta.url), output);
